/**
 * Lookup coordinates for a given barangay, defaulting to Lagonoy Central Headend if not found.
 */
export const getBarangayCoordinates = (barangayName: string): { lat: number; lng: number; city: string } => {
  if (!barangayName) return { lat: 13.6870, lng: 123.5210, city: 'Lagonoy' };

  // Direct match
  if (BARANGAY_COORDINATES[barangayName]) {
    return BARANGAY_COORDINATES[barangayName];
  }

  // Normalized search (case-insensitive and trimmed)
  const norm = barangayName.toLowerCase().trim().replace(/^brgy\.?\s*/i, '');
  for (const [key, coords] of Object.entries(BARANGAY_COORDINATES)) {
    if (key.toLowerCase().includes(norm) || norm.includes(key.toLowerCase())) {
      return coords;
    }
  }

  return { lat: 13.6870, lng: 123.5210, city: 'Lagonoy' };
};

